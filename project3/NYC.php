                <section class="content-box" id="Dutch-Rule">
                    <h2>Dutch rule</h2>
                    <img src="./images/NewAmsterdam.jpg" alt="NewAmsterdam" width="428" height="291">

                    <p>A permanent European presence near New York Harbor was established in 1624, making New York the 12th-oldest
                        continuously occupied European-established settlement in the continental United States, with the founding of
                        a Dutch fur trading settlement on Governors Island. In 1625, construction was started on a citadel and Fort
                        Amsterdam, later called Nieuw Amsterdam (New Amsterdam), on present-day Manhattan Island.
                    </p>
                    <p>
                        The colony of New Amsterdam extended from the southern tip of Manhattan to modern-day Wall Street, where a
                        12-foot (3.7 m) wooden stockade was built in 1653 to protect against Native American and English raids. In
                        1626, the Dutch colonial Director-General Peter Minuit, as charged by the Dutch West India Company,
                        purchased the island of Manhattan from the Canarsie, a small Lenape band, for "the value of 60 guilders"
                        (about $900 in 2018). A frequently told but disproved legend claims that Manhattan was purchased for $24
                        worth of glass beads.
                    </p>
                    <p>
                        Following the purchase, New Amsterdam grew slowly. To attract settlers, the Dutch instituted the patroon
                        system in 1628, whereby wealthy Dutchmen (patroons, or patrons) who brought 50 colonists to New Netherland
                        would be awarded land, local political autonomy, and rights to participate in the lucrative fur trade. This
                        program had little success.
                    </p>
                    <p>
                        Since 1621, the Dutch West India Company had operated as a monopoly in New Netherland, on authority granted
                        by the Dutch States General. In 1639–1640, in an effort to bolster economic growth, the Dutch West India
                        Company relinquished its monopoly over the fur trade, leading to growth in the production and trade of food,
                        timber, tobacco, and slaves (particularly with the Dutch West Indies).
                    </p>
                    <p>
                        In 1647, Peter Stuyvesant began his tenure as the last Director-General of New Netherland. During his
                        tenure, the population of New Netherland grew from 2,000 to 8,000. Stuyvesant has been credited with
                        improving law and order; however, he earned a reputation as a despotic leader. He instituted regulations on
                        liquor sales, attempted to assert control over the Dutch Reformed Church, and blocked other religious groups
                        from establishing houses of worship.</p>

                </section>

                <section class="content-box" id="English-Rule">
                    <h2>English rule</h2>
                    <p>In 1664, unable to summon any significant resistance, Stuyvesant surrendered New Amsterdam to English troops,
                        led by Colonel Richard Nicolls, without bloodshed. The terms of the surrender permitted Dutch residents to
                        remain in the colony and allowed for religious freedom.
                    </p>
                    <p>
                        In 1667, during negotiations leading to the Treaty of Breda after the Second Anglo-Dutch War, the victorious
                        Dutch decided to keep the nascent plantation colony of what is now Suriname, which they had gained from the
                        English, and in return the English kept New Amsterdam. The settlement was promptly renamed "New York" after
                        the Duke of York (the future King James II and VII). The duke gave part of the colony to proprietors George
                        Carteret and John Berkeley.
                    </p>
                    <p>
                        On August 24, 1673, during the Third Anglo-Dutch War, Anthony Colve of the Dutch navy seized New York at the
                        behest of Cornelis Evertsen the Youngest and rechristened it "New Orange" after William III, the Prince of
                        Orange. The Dutch soon returned the island to England under the Treaty of Westminster of November 1674.
                    </p>
                    <p>
                        Several intertribal wars among the Native Americans and epidemics brought on by contact with the Europeans
                        caused sizable population losses for the Lenape between 1660 and 1670. By 1700, the Lenape population had
                        diminished to 200. New York experienced several yellow fever epidemics in the 18th century, losing ten
                        percent of its population in 1702 alone.
                    </p>
                    <p>
                        In the early 18th century, New York grew in importance as a trading port while as a part of the colony of
                        New York. It became a center of slavery, with 42% of households enslaving Africans by 1730. Most were
                        domestic slaves; others were hired out as labor. Slavery became integrally tied to New York's economy
                        through the labor of slaves throughout the port, and the banking and shipping industries trading with the
                        American South. During construction in Foley Square in the 1990s, the African Burying Ground was discovered;
                        the cemetery included 10,000 to 20,000 graves of colonial-era Africans, some enslaved and some free.
                    </p>
                    <p>
                        The 1735 trial and acquittal in Manhattan of John Peter Zenger, who had been accused of seditious libel
                        after criticizing colonial governor William Cosby, helped to establish freedom of the press in North
                        America. In 1754, Columbia University was founded.
                    </p>

                </section>

                <section class="content-box" id="post-revolution">
                    <h2>Post-revolutionary period and early 19th century</h2>
                    <img src="./images/Washington.jpg" alt="Washington" width="333" height="225">

                    <p>In January 1785, the assembly of the Congress of the Confederation made New York City the national capital.
                        New York was the last capital of the United States under the Articles of Confederation and the first under
                        the Constitution. As the capital, New York City hosted the inauguration of the first President, George
                        Washington, and the first Congress, at Federal Hall on Wall Street. Congress drafted the Bill of Rights
                        there. The Supreme Court held its first organizational sessions in New York in 1790.
                    </p>
                    <p>
                        In 1790, for the first time, New York City surpassed Philadelphia as the nation's largest city. At the end
                        of 1790, the national capital was moved to Philadelphia.
                    </p>
                    <p>
                        During the 19th century, New York City's population grew from 60,000 to 3.43 million. Under New York State's
                        gradual emancipation act of 1799, children of slave mothers were to be eventually liberated but to be held
                        in indentured servitude until their mid-to-late twenties. Together with slaves freed by their masters after
                        the Revolutionary War and escaped slaves, a significant free-Black population gradually developed in
                        Manhattan. The New York Manumission Society worked for abolition and established the African Free School to
                        educate Black children. It was not until 1827 that slavery was completely abolished in the state. Free
                        Blacks struggled with discrimination and interracial abolitionist activism continued. New York City's
                        population jumped from 123,706 in 1820 (10,886 of whom were Black and of which 518 were enslaved) to 312,710
                        by 1840 (16,358 of whom were Black).
                    </p>
                    <p>
                        Also in the 19th century, the city was transformed by both commercial and residential development relating
                        to its status as a national and international trading center, as well as by European immigration,
                        respectively. The city adopted the Commissioners' Plan of 1811, which expanded the city street grid to
                        encompass almost all of Manhattan. The 1825 completion of the Erie Canal through central New York connected
                        the Atlantic port to the agricultural markets and commodities of the North American interior via the Hudson
                        River and the Great Lakes. Local politics became dominated by Tammany Hall, a political machine supported by
                        Irish and German immigrants. In 1831, New York University was founded.
                    </p>
                    <p>
                        Several prominent American literary figures lived in New York during the 1830s and 1840s, including William
                        Cullen Bryant, Washington Irving, Herman Melville, Rufus Wilmot Griswold, John Keese, Nathaniel Parker
                        Willis, and Edgar Allan Poe. Members of the business elite lobbied for the establishment of Central Park,
                        which in 1857 became the first landscaped park in an American city.
                    </p>
                    <p>
                        The Great Irish Famine brought a large influx of Irish immigrants, of whom more than 200,000 were living in
                        New York by 1860, representing over a quarter of the city's population. Extensive immigration from the
                        German provinces meant that Germans comprised another 25% of New York's population by 1860.
                    </p>

                </section>

                <section class="content-box" id="early-20th">
                    <h2>Late 19th and early 20th century</h2>
                    <img src="./images/NYC_Mulberry.jpg" alt="NYC_Mulberry" width="427" height="315">
            
                    <p>In 1886, the Statue of Liberty, a gift from France, was dedicated in New York Harbor. The statue welcomed 14
                        million immigrants as they arrived via Ellis Island by ship in the late 19th and early 20th centuries, and
                        is a symbol of the United States and American ideals of liberty and peace.
                    </p>
                    <p>
                        In 1898, the City of New York was formed with the consolidation of Brooklyn (until then a separate city),
                        the County of New York (which then included parts of the Bronx), the County of Richmond, and the western
                        portion of the County of Queens. The opening of the New York City Subway in 1904, first built as separate
                        private systems, helped bind the new city together. Throughout the first half of the 20th century, the city
                        became a world center for industry, commerce, and communication.
                    </p>
                    <p>
                        In 1904, the steamship General Slocum caught fire in the East River, killing 1,021 people. In 1911, the
                        Triangle Shirtwaist Factory fire, the city's worst industrial disaster, killed 146 garment workers and
                        spurred the growth of the International Ladies' Garment Workers' Union and major improvements in factory
                        safety standards.
                    </p>
                    <p>
                        New York's non-White population was 36,620 in 1890. New York City was a prime destination in the early 20th
                        century for Blacks during the Great Migration from the American South, and by 1916, New York City had the
                        largest urban African diaspora in North America. The Harlem Renaissance of literary and cultural life
                        flourished during the era of Prohibition. The larger economic boom generated construction of skyscrapers
                        competing in height.
                    </p>
                    <p>
                        New York City became the most populous urbanized area in the world in the early 1920s, overtaking London.
                        The metropolitan area surpassed 10 million in the early 1930s, becoming the first megacity. The Great
                        Depression saw the election of reformer Fiorello La Guardia as mayor and the fall of Tammany Hall after
                        eighty years of political dominance.
                    </p>
                    <p>
                        Returning World War II veterans created a post-war economic boom and the development of large housing tracts
                        in eastern Queens and Nassau County, with Wall Street leading America's place as the world's dominant
                        economic power. The United Nations headquarters was completed in 1952, solidifying New York's global
                        geopolitical influence, and the rise of abstract expressionism in the city precipitated New York's
                        displacement of Paris as the center of the art world.
                    </p>
      
                </section>

