                <section class="content-box" id="About">
                    <h2>About</h2>
                    <img src="./images/NY_Map.png" alt="NY_Map" width="340" height="256">
                    <p>
                        New York, <em>often called New York City or NYC</em>, is the most populous city in the United States,
                        located at the southern tip of New York State on one of the world's largest natural harbors. The city
                        comprises five
                        boroughs, each coextensive with a respective county. The city is the geographical and demographic center of
                        both the
                        Northeast megalopolis and the New York metropolitan area, the largest metropolitan area in the United States
                        by both population and urban area. New York is a global center of finance and commerce, culture, technology,
                        entertainment and media, academics and scientific output, the arts and fashion, and, as home to the
                        headquarters of the United Nations, international diplomacy.</p>
            
                    <p>
                        With an estimated population in 2023 of
                        <strong>8,258,035</strong> distributed over
                        <strong>300.46 square miles (778.2 km2)</strong>, the city is
                        <strong><em>the most densely populated major city in the United States</em></strong>.
                        New York City has more than double the population of Los Angeles, the nation's second-most populous city.
                        With more than 20.1 million people in its metropolitan statistical area and 23.5 million in its combined
                        statistical area as of 2020, New York City is one of the world's most populous megacities. The city and its
                        metropolitan area are the premier gateway for legal immigration to the United States. As many as 800
                        languages are spoken in New York City, making it the most linguistically diverse city in the world. In 2021,
                        the city was home to nearly 3.1 million residents born outside the United States, the largest foreign-born
                        population of any city in the world.
                    </p>

                </section>
                
                <section class="content-box" id="Early-History">
                    <h2>Early History</h2>
                    <p>
                        In the pre-Columbian era, the area of present-day New York City was inhabited by Algonquians, including the
                        Lenape. Their homeland, known as Lenapehoking, included the present-day areas of Staten Island, Manhattan,
                        the
                        Bronx, the western portion of Long Island (including Brooklyn and Queens), and the Lower Hudson Valley.
                    </p>
                    <p>
                        The first documented visit into New York Harbor by a European was in 1524 by explorer Giovanni da
                        Verrazzano. He
                        claimed the area for France and named it Nouvelle Angoulême (New Angoulême). A Spanish expedition, led by
                        the
                        Portuguese captain Estêvão Gomes sailing for Emperor Charles V, arrived in New York Harbor in January 1525
                        and
                        charted the mouth of the Hudson River, which he named Río de San Antonio ('Saint Anthony's River').
                    </p>
                    <p>
                        In 1609, the English explorer Henry Hudson rediscovered New York Harbor while searching for the Northwest
                        Passage to the Orient for the Dutch East India Company. He sailed up what the Dutch called North River (now
                        the
                        Hudson River), named first by Hudson as the Mauritius after Maurice, Prince of Orange.
                    </p>
                    <p>
                        Hudson claimed the region for the Dutch East India Company. In 1614, the area between Cape Cod and Delaware
                        Bay
                        was claimed by the Netherlands and called Nieuw-Nederland ('New Netherland'). The first non–Native American
                        inhabitant of what became New York City was Juan Rodriguez, a merchant from Santo Domingo who arrived in
                        Manhattan during the winter of 1613–14, trapping for pelts and trading with the local population as a
                        representative of the Dutch.
                    </p>

                </section>
                
                <section class="content-box" id="revolution">

                    <h2>American Revolution</h2>
                    <p>The Stamp Act Congress met in New York in October 1765, as the Sons of Liberty organization emerged in the
                        city and skirmished over the next ten years with British troops stationed there. The Battle of Long Island,
                        the largest battle of the American Revolutionary War, was fought in August 1776 within modern-day Brooklyn.
                        A British rout of the Continental Army at the Battle of Fort Washington in November 1776 eliminated the last
                        American stronghold in Manhattan, causing George Washington and his forces to retreat across the Hudson
                        River to New Jersey, pursued by British forces.
                    </p>
                    <p>
                        After the battle, in which the Americans were defeated, the British made the city their military and
                        political base of operations in North America. The city was a haven for Loyalist refugees and escaped slaves
                        who joined the British lines for freedom promised by the Crown, with as many as 10,000 escaped slaves
                        crowded into the city during the British occupation, the largest such community on the continent. When the
                        British forces evacuated New York at the close of the war in 1783, they transported thousands of freedmen
                        for resettlement in Nova Scotia, England, and the Caribbean.
                    </p>
                    <p>
                        The attempt at a peaceful solution to the war took place at the Conference House on Staten Island between
                        American delegates, including Benjamin Franklin, and British general Lord Howe on September 11, 1776.
                        Shortly after the British occupation began, the Great Fire of New York destroyed nearly 500 buildings, about
                        a quarter of the structures in the city, including Trinity Church.
                    </p>
                    
                </section>

                <section class="content-box" id="civil-war">
                    <h2>The American Civil War</h2>
                    <p>Democratic Party candidates were consistently elected to local office, increasing the city's ties to the
                        South and its dominant party. In 1861, Mayor Fernando Wood called on the aldermen to declare independence
                        from Albany and the United States after the South seceded, but his proposal was not acted on. Anger at new
                        military conscription laws during the American Civil War (1861–1865), which spared wealthier men who could
                        afford to hire a substitute, led to the Draft Riots of 1863, whose most visible participants were ethnic
                        Irish working class.
                    </p>
                    <p>
                        The draft riots deteriorated into attacks on New York's elite, followed by attacks on Black New Yorkers
                        after fierce competition for a decade between Irish immigrants and Black people for work. Rioters burned the
                        Colored Orphan Asylum to the ground. At least 120 people were killed. Eleven Black men were lynched over
                        five days, and the riots forced hundreds of Blacks to flee. The Black population in Manhattan fell below
                        10,000 by 1865. The White working class had established dominance. It was one of the worst incidents of
                        civil unrest in American history.
                    </p>
   
                </section>

                <section class="content-box" id="21st-century">
                    <h2>Late 20th and early 21st centuries</h2>
                    <img src="./images/WTC.jpg" alt="WTC" width="427" height="293">

                    <p>In 1969, the Stonewall riots were a series of violent protests by members of the gay community against a
                        police raid that took place in the early morning of June 28, 1969, at the Stonewall Inn in Greenwich
                        Village. They are widely considered to be the single most important event leading to the gay liberation
                        movement and the modern fight for LGBT rights. Wayne R. Dynes, author of the Encyclopedia of Homosexuality,
                        wrote that drag queens were the only "transgender folks around" during the Stonewall riots. The transgender
                        community in New York City played a significant role in fighting for LGBT equality.
                    </p>
                    <p>
                        In the 1970s, job losses due to industrial restructuring caused New York City to suffer from economic
                        problems and rising crime rates. Growing fiscal deficits in 1975 led the city to appeal to the federal
                        government for financial aid; President Gerald Ford gave a speech denying the request, which was paraphrased
                        on the front page of the New York Daily News as "FORD TO CITY: DROP DEAD". The Municipal Assistance
                        Corporation was formed and granted oversight authority over the city's finances. While a resurgence in the
                        financial industry greatly improved the city's economic health in the 1980s, New York's crime rate continued
                        to increase through that decade and into the beginning of the 1990s.
                    </p>
                    <p>
                        New York City's population exceeded 8 million for the first time in the 2000 census; further records were
                        set in the 2010 and 2020 censuses. Important new economic sectors, such as Silicon Alley, emerged.
                    </p>
                    <p>
                        The year 2000 was celebrated with fanfare in Times Square. New York City suffered the bulk of the economic
                        damage and largest loss of human life in the aftermath of the September 11, 2001, attacks. Two of the four
                        hijacked airliners were flown into the twin towers of the World Trade Center, resulting in the collapse of
                        both buildings and the deaths of 2,753 people, including 343 first responders from the New York City Fire
                        Department and 71 law enforcement officers.
                    </p>
                    <p>
                        The area was rebuilt with a new World Trade Center, the National September 11 Memorial and Museum, and other
                        new buildings and infrastructure, including the World Trade Center Transportation Hub, the city's
                        third-largest hub. The new One World Trade Center is the tallest skyscraper in the Western Hemisphere and
                        the world's seventh-tallest building by pinnacle height, with its spire reaching a symbolic 1,776 feet
                        (541.3 m), a reference to the year of American independence.
                    </p>
                    <p>
                        The Occupy Wall Street protests in Zuccotti Park in the Financial District of Lower Manhattan began on
                        September 17, 2011, receiving global attention and popularizing the Occupy movement against social and
                        economic inequality worldwide.
                    </p>
                    <p>
                        New York City was heavily impacted by Hurricane Sandy in October 2012, including flooding that led to the
                        days-long shutdown of the subway system, and flooding of all East River subway tunnels and of all road
                        tunnels entering Manhattan except the Lincoln Tunnel. The New York Stock Exchange closed for two days due to
                        weather for the first time since the Great Blizzard of 1888. At least 43 people died in New York City as a
                        result of Sandy, and the economic losses in New York City were estimated to be roughly $19 billion. The
                        disaster spawned long-term efforts towards infrastructural projects to counter climate change and rising
                        seas, with $15 billion in federal funding received through 2022 towards those resiliency efforts.
                    </p>
                    <p>
                        In March 2020, the first case of COVID-19 in the city was confirmed. With its population density and
                        extensive exposure to global travelers, the city rapidly replaced Wuhan, China as the global epicenter of
                        the pandemic during the early phase, straining the city's healthcare infrastructure. Through March 2023, New
                        York City recorded more than 80,000 deaths from COVID-19-related complications.
                    </p>

                </section>

